function norm(s) {
  return String(s).toLowerCase()
    .replace(/[‘’]/g, "'")
    .replace(/[^a-z0-9._+/\- ]/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

/* Verb families where suffix stripping alone leaves the forms apart —
   "simulated" stems to simulat, "simulation" does not, so a question about
   whether anything was simulated missed the note that says nothing was.
   These are collapsed to one canonical token before stemming. */
const LEMMA = {
  simulate: 'simulation', simulated: 'simulation', simulating: 'simulation',
  simulations: 'simulation', sim: 'simulation', sims: 'simulation',
  confirm: 'confirm', confirmed: 'confirm', confirmation: 'confirm', confirms: 'confirm',
  verify: 'verify', verified: 'verify', verification: 'verify', verifies: 'verify',
  configure: 'config', configured: 'config', configuration: 'config',
  implement: 'implement', implemented: 'implement', implementation: 'implement',
  validate: 'validation', validated: 'validation',
  compile: 'compile', compiled: 'compile', compilation: 'compile',
  synthesise: 'synthesis', synthesize: 'synthesis', synthesised: 'synthesis',
  synthesized: 'synthesis', synthesis: 'synthesis',
  measure: 'measure', measured: 'measure', measurement: 'measure',
  isolate: 'isolation', isolated: 'isolation',
  test: 'test', tested: 'test', testing: 'test', tests: 'test',
};

/* Light stemming: enough to join plural/singular, not enough to cause
   collisions between unrelated project terms. */
function stem(t) {
  if (LEMMA[t]) return LEMMA[t];
  if (t.length > 4 && t.endsWith('ies')) return t.slice(0, -3) + 'y';
  if (t.length > 4 && t.endsWith('ses')) return t.slice(0, -2);
  if (t.length > 3 && t.endsWith('s') && !t.endsWith('ss')) return t.slice(0, -1);
  if (t.length > 5 && t.endsWith('ing')) return t.slice(0, -3);
  if (t.length > 5 && t.endsWith('ed')) return t.slice(0, -2);
  return t;
}

function tokens(s, { expand = false } = {}) {
  const raw = norm(s).split(' ').filter(Boolean);
  const out = [];
  for (const t of raw) {
    if (t.length < 2 || STOP.has(t)) continue;
    out.push(stem(t));
    if (expand && ALIAS[t]) for (const a of ALIAS[t].split(' ')) if (!STOP.has(a)) out.push(stem(a));
  }
  return out;
}

/* Text for a chunk, whichever field it stores it in. */
function chunkText(c) {
  if (c.text) return c.text;
  if (c.code) return c.code.replace(/^\s*(\/\/|%)+\s?/gm, '');
  return '';
}

/* ---------------------------------------------------------------- index */

const IDX = (() => {
  const chunks = typeof KB_CHUNKS !== 'undefined' ? KB_CHUNKS : [];
  const df = Object.create(null);
  const docs = chunks.map(c => {
    const body = tokens(chunkText(c));
    const head = tokens(`${c.title || ''} ${c.heading || ''} ${(c.topics || []).join(' ')}`);
    const tf = Object.create(null);
    // Heading terms counted 3x — a chunk titled "current sense path" should
    // beat one that merely mentions the words in passing.
    for (const t of body) tf[t] = (tf[t] || 0) + 1;
    for (const t of head) tf[t] = (tf[t] || 0) + 3;
    for (const t of Object.keys(tf)) df[t] = (df[t] || 0) + 1;
    return { c, tf, len: body.length + head.length * 3 };
  });
  const avgdl = docs.reduce((a, d) => a + d.len, 0) / (docs.length || 1);
  const byId = new Map(docs.map(d => [d.c.id, d]));
  return { docs, df, avgdl, N: docs.length, byId };
})();

/* Multi-word project terms carry far more signal than their parts: "active
   high", "current sense", "non overlap". Matching them as phrases is what
   stops `wire active = ...` in the PWM module out-ranking the board note
   that actually states the DISABLE polarity. */
function bigrams(ts) {
  const out = [];
  for (let i = 0; i < ts.length - 1; i++) out.push(ts[i] + ' ' + ts[i + 1]);
  return out;
}

const PHRASE_CACHE = new Map();
function phraseHits(chunk, qBigrams) {
  if (!qBigrams.length) return 0;
  let hay = PHRASE_CACHE.get(chunk.id);
  if (hay === undefined) {
    hay = tokens(`${chunk.title || ''} ${chunk.heading || ''} ${chunkText(chunk)}`).join(' ');
    PHRASE_CACHE.set(chunk.id, hay);
  }
  let n = 0;
  for (const b of qBigrams) if (hay.includes(b)) n++;
  return n;
}

/* --------------------------------------------------------------- scoring */

const K1 = 1.4, B = 0.72;

function bm25(doc, qTokens) {
  let s = 0;
  for (const t of qTokens) {
    const f = doc.tf[t];
    if (!f) continue;
    const idf = Math.log(1 + (IDX.N - IDX.df[t] + 0.5) / (IDX.df[t] + 0.5));
    s += idf * (f * (K1 + 1)) / (f + K1 * (1 - B + B * doc.len / IDX.avgdl));
  }
  return s;
}

/* Source priority, exactly as specified: my project files first, then
   datasheets and official manuals, then official docs, then app notes,
   with video treated as a learning aid rather than evidence. */
const TIER_W = { 1: 1.00, 2: 0.74, 3: 0.64, 4: 0.52, 5: 0.30 };

const KIND_W = { doc: 1.00, rtl: 1.00, matlab: 1.00, tb: 0.92, link: 0.80 };

