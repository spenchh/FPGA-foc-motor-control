/* ===========================================================================
   retrieval.js — the search engine behind the project assistant

   Pure logic, no DOM. Given a question it returns ranked chunks from
   KB_CHUNKS (generated by tools/build-kb.mjs) plus the intent it detected,
   so the answer layer can lead with a specific fact instead of a topic essay.

   Ranking, in order of influence:
     1. BM25 over the chunk text, with title and heading weighted up
     2. Source tier      project files > datasheets > official docs > app
                         notes > video
     3. Topic agreement  question topics vs chunk topics
     4. Mode bias        the answer mode the user picked
     5. Recency          superseded notes are pushed far down
   =========================================================================== */

