/* --------------------------------------------------------------- search */

function search(question, { mode = 'quick', limit = 8 } = {}) {
  const qt = tokens(question, { expand: true });
  if (!qt.length) return { hits: [], intent: detectIntent(question), qTokens: [] };

  const intent = detectIntent(question);
  const m = MODES[mode] || MODES.quick;
  const modeTopics = new Set(m.topics);
  const qTopics = new Set(intent.topics);
  const qBigrams = bigrams(tokens(question));

  const scored = [];
  for (const doc of IDX.docs) {
    let s = bm25(doc, qt);
    if (s <= 0) continue;
    const c = doc.c;

    s *= TIER_W[c.tier] || 0.5;
    s *= KIND_W[c.kind] || 1;

    const ph = phraseHits(c, qBigrams);
    if (ph) s *= 1 + Math.min(ph, 3) * 0.45;

    // A question about a specification wants the note that states it, not the
    // source line that happens to reuse the word as an identifier.
    if (intent.intents.includes('spec') && (c.kind === 'rtl' || c.kind === 'tb') && !ph) s *= 0.45;

    // Topic agreement with the question is a strong, cheap relevance signal.
    const ct = c.topics || [];
    let overlap = 0;
    for (const t of ct) if (qTopics.has(t)) overlap++;
    if (overlap) s *= 1 + Math.min(overlap, 3) * 0.22;

    // Mode nudges the same corpus toward the lens the user asked for.
    for (const t of ct) if (modeTopics.has(t)) { s *= 1.18; break; }
    if (m.kinds[c.kind]) s *= m.kinds[c.kind];

    // Intent-specific shaping.
    if (intent.intents.includes('file-list') && (c.kind === 'rtl' || c.kind === 'tb')) s *= 1.3;
    if (intent.intents.includes('vivado') && ct.includes('vivado')) s *= 1.3;
    if (intent.intents.includes('blockers') && (c.status === 'open' || ct.includes('blocker'))) s *= 1.5;
    if (intent.intents.includes('next-steps') && (c.status === 'open' || ct.includes('next-steps'))) s *= 1.45;
    if (intent.intents.includes('concept') && c.kind === 'link' && c.tier <= 3) s *= 1.2;

    // Old revisions stay reachable for "what changed", never for "what is".
    if (c.superseded) s *= 0.28;

    scored.push({ chunk: c, score: s });
  }

  scored.sort((a, b) => b.score - a.score);

  // Keep at most two chunks per source file so one long note cannot crowd out
  // every other source — this is what stopped answers being one wall of text.
  const perFile = new Map();
  const hits = [];
  for (const h of scored) {
    const k = h.chunk.file;
    const n = perFile.get(k) || 0;
    if (n >= 2) continue;
    perFile.set(k, n + 1);
    hits.push(h);
    if (hits.length >= limit) break;
  }

  return { hits, intent, qTokens: qt, mode: m };
}

/* -------------------------------------------------- sentence extraction */

function splitSentences(text) {
  return text
    .split('\n')
    .flatMap(line => {
      const t = line.trim();
      if (!t) return [];
      // Keep bullets whole; they are already one thought each.
      if (/^[-*•]\s+/.test(t) || /^\d+\.\s+/.test(t)) return [t.replace(/^[-*•]\s+/, '').replace(/^\d+\.\s+/, '')];
      return t.split(/(?<=[.!?])\s+(?=[A-Z(])/);
    })
    .map(s => s.trim())
    .filter(s => s.length > 24 && s.length < 400);
}

/* The single most useful thing the engine does: pick the sentences inside a
   chunk that actually answer the question, so the reply leads with the fact
   rather than reprinting the section. */
function bestSentences(chunk, qTokens, n = 2) {
  const sents = splitSentences(chunkText(chunk));
  if (!sents.length) return [];
  const qset = new Set(qTokens);
  const scored = sents.map((s, i) => {
    const st = tokens(s);
    let hit = 0;
    const seen = new Set();
    for (const t of st) if (qset.has(t) && !seen.has(t)) { hit++; seen.add(t); }
    // Coverage of the question beats sheer length; a short exact line wins.
    let score = hit / Math.sqrt(st.length + 4);
    if (i === 0) score *= 1.15;                       // lead sentence carries the claim
    if (/\b(is|are|must|does|use[sd]?|means)\b/.test(s)) score *= 1.05;
    return { s, score, hit };
  }).filter(x => x.hit > 0);

  scored.sort((a, b) => b.score - a.score);
  return scored.slice(0, n).map(x => x.s);
}

/* ------------------------------------------------------------ confidence */

/* Confidence describes how well the corpus covers the question — never how
   true the underlying engineering claim is. */
function confidenceOf(hits, qTokens) {
  if (!hits.length) return { level: 'none', label: 'No source found', pct: 0, coverage: 0 };
  const top = hits[0];
  const tierOk = top.chunk.tier === 1;

  /* Coverage — how much of what was asked actually appears in the winning
     chunk — matters more than raw BM25, which inflates on short documents.
     Without this the engine reported 100% on a 4.2 score with one term hit. */
  const uniq = [...new Set(qTokens)];
  const doc = IDX.byId.get(top.chunk.id);
  const present = doc ? uniq.filter(t => doc.tf[t]).length : 0;
  const coverage = uniq.length ? present / uniq.length : 0;

  const strength = Math.min(1, top.score / 14);
  const margin = hits.length > 1 ? top.score / (hits[1].score || 0.0001) : 1.5;

  let pct = Math.round(100 * (0.62 * coverage + 0.38 * strength));
  if (tierOk) pct += 6;
  if (margin > 1.7) pct += 6;
  if (top.chunk.superseded) pct -= 32;
  pct = Math.max(3, Math.min(99, pct));

  let level = 'low', label = 'Weak match — treat as a pointer, not an answer';
  if (pct >= 60 && coverage >= 0.5) { level = 'high'; label = 'Strong match in project files'; }
  else if (pct >= 33) { level = 'medium'; label = 'Partial match'; }
  if (!tierOk && level === 'high') { level = 'medium'; label = 'Strong match, but external source'; }
  return { level, label, pct, coverage };
}

/* Group what was retrieved by how settled it is, so the answer can show
   Confirmed / Inferred / Open separately instead of blending them. */
function groupByStatus(hits) {
  const g = { confirmed: [], inferred: [], open: [] };
  for (const h of hits) (g[h.chunk.status] || g.confirmed).push(h);
  return g;
}

