function followUps(hits, asked, max = 3) {
  const seen = new Set([norm(asked)]);
  const out = [];
  const topics = [];
  for (const h of hits) for (const t of (h.chunk.topics || [])) if (!topics.includes(t)) topics.push(t);
  for (const t of topics) {
    for (const q of (TOPIC_QUESTIONS[t] || [])) {
      if (seen.has(norm(q))) continue;
      seen.add(norm(q));
      out.push(q);
      if (out.length >= max) return out;
    }
  }
  return out;
}

